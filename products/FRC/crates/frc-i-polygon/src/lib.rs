//! # frc-i-polygon — полигон FRC-I
//!
//! Арена для двух родов задач:
//! - **A/B калибровок кодера** (линии версий): стороны задаются env-ручками
//!   reference-кодера (см. `documents/codecs/frc-i.md` §11); каждая сторона —
//!   отдельный процесс `flora-codec`, поэтому `OnceLock`-инициализация ручек
//!   сохраняется естественно, а условия замера равны у всех участников;
//! - **честного сравнения с внешними кодеками**: JPEG/WebP/AVIF через ffmpeg,
//!   JXL — нативными `cjxl`/`djxl` (урок §11.10: ffmpeg libjxl ≠ cjxl).
//!
//! Принципы равных условий:
//! - все участники — внешние процессы: одинаковый вклад запуска и PNG-IO
//!   в замеры скорости;
//! - метрики PSNR (RGB и Y BT.709) и SSIM (окна 8×8, шаг 4 → dB) считаются
//!   **одним и тем же кодом** этого crate по PNG-парам; SSIMULACRA2 и
//!   butteraugli pnorm — внешними бинарями libjxl (опционально, при
//!   отсутствии деградируют в `None`);
//! - сводка — **BD-rate** (PCHIP-интерполяция, как в JVET/AOM CTC), плюс
//!   сторожевые критерии линий: **размер лестницы** (сдвиг рабочей точки
//!   q↔байты) и **iso-size** (дельта качества на ближайшем размере).
//!
//! Корпус: детерминированная целочисленная синтетика (бит-в-бит на всех
//! платформах, кэшируется в PNG) + эталонные наборы (`fetch`: Kodak 24,
//! picsum 12) + любые пользовательские `*.png` в каталоге корпуса.

