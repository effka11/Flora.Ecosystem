//! # fpp-core — детерминированное ядро FPP (метрики натуральности, NS)
//!
//! Нормативная спецификация — [`Documents/fpp/FPP-SIGNALS.md`]; протокольная привязка —
//! FPP §8.3. Поведение бит-в-бит зафиксировано golden-вектором
//! `Documents/test-vectors/personhood/personhood-naturalness-v1.json`
//! (регенерация: `cargo run -p fpp-core --example gen_personhood_vectors`).
//!
//! Правила детерминизма (FPP-SIGNALS §7):
//! - только целочисленная арифметика; выходы — промилле (‰, 0..=1000);
//! - деление — усечение к нулю; квадратный корень — целочисленный floor (`isqrt`);
//! - переполнение невозможно по построению (входы зажимаются, промежуточные — `u128`/`i128`);
//! - никакого float ни в одном пути (совместимо с инвариантом FGP §8.1).
//!
//! Состав:
//! - [`temporal`] — NS-T1 burstiness, NS-T2 суточный профиль (rest/peak/self-similarity);
//! - [`streams`] — NS-T3 односторонний CUSUM по агрегатным потокам;
//! - [`device`] — NS-D2/NS-D3 классификация девайс-связности и текучки;
//! - [`piecewise`] — калибровочные кривые «метрика → натуральность» (R2-параметры);
//! - [`score`] — свод сигналов, классы Natural/Watch/Investigate с гистерезисом.
//!
//! Ядро advisory-only: ни одна функция не выносит вердикт — только приоритизацию
//! следствия V-01 (FPP §8.3). Зависимостей на модули workspace нет: компилируется
//! в wasm32 и переносимо в независимые верификаторы.

pub mod device;
pub mod piecewise;
pub mod score;
pub mod streams;
pub mod temporal;

/// Версия протокольных артефактов ядра (поле `protocolVersion` векторов).
pub const PROTOCOL_VERSION: u32 = 1;

/// Целочисленная шкала промилле: 1000 = максимум (для скора — «максимально естественно»).
pub const PERMILLE: u32 = 1000;
