//! # frc-v-polygon — кросс-кодек полигон FRC-V
//!
//! Арена для честного сравнения FRC-V с внешними кодеками (x264, x265,
//! libvpx-VP9, SVT-AV1, libaom-AV1) и для отслеживания собственного прогресса
//! между версиями энкодера.
//!
//! Принципы равных условий:
//! - **все кодеки — внешние процессы** (FRC-V через `frc-v` CLI, остальные —
//!   через `ffmpeg`): одинаковый вклад запуска процесса и y4m-IO в замеры;
//! - **1 поток** у всех энкодеров, общий `keyint`;
//! - размер потока — **elementary stream без контейнера** (для IVF/FRV
//!   вычитается оверхед контейнера, h264/hevc и так сырые);
//! - метрики (PSNR/SSIM) считаются **одним и тем же кодом** (`frc_v::metrics`)
//!   по y4m-парам; VMAF — libvmaf из ffmpeg (опционально);
//! - сводка — **BD-rate** (PCHIP-интерполяция, как в JVET/AOM CTC) против
//!   каждого конкурента и против собственного baseline-снимка.
//!
//! Корпус: детерминированная целочисленная синтетика (бит-в-бит на всех
//! платформах) + эталонные клипы xiph/derf (`fetch`).

