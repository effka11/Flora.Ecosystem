import { useThemeStore } from "@/stores/themeStore";

/** Заглушка для неактивной части экрана: значение не меняется — ререндера нет. */
const INACTIVE_EPOCH = -1;

/**
 * Перерисовка на смену палитры только у видимой части экрана.
 *
 * Полная подписка `useFloraTheme()` нужна экранам, которые видны всегда
 * (оболочка, таб-бар). Внутри пейджера настроек смонтированы все секции,
 * но видна одна: неактивные не должны участвовать в кадре переключения темы.
 * Когда секция станет активной, `active` меняется → компонент рендерится
 * и читает уже актуальную палитру.
 */
export function useFloraThemeRefresh(active = true): void {
  useThemeStore((state) => (active ? state.version : INACTIVE_EPOCH));
}
