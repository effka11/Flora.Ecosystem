pub(crate) fn glyph(c: char) -> &'static [u8; 7] {
    let code = c as u32;
    let index = if (0x20..=0x7E).contains(&code) {
        (code - 0x20) as usize
    } else {
        (b'?' - 0x20) as usize
    };
    &GLYPHS[index]
}

/// Inclusive width of `text` at an integer scale `1..=4`.
pub(crate) fn text_width(text: &str, scale: i32) -> i32 {
    let count = text.chars().count() as i32;
    if count == 0 {
        0
    } else {
        (count * ADVANCE - 1) * scale
    }
}

pub(crate) fn text_height(scale: i32) -> i32 {
    GLYPH_HEIGHT * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_has_every_printable_ascii_glyph() {
        assert_eq!(GLYPHS.len(), 95);
        assert_eq!(GLYPHS[0], [0; 7], "space is blank");
        assert_eq!(GLYPHS[(b'?' - 0x20) as usize][0], 0x0E);
        assert_eq!(GLYPHS[(b'#' - 0x20) as usize][1], 0x1F);
    }

    #[test]
    fn unknown_characters_fall_back_to_a_question_mark() {
        assert_eq!(glyph('\u{1F600}'), glyph('?'));
        assert_eq!(glyph('\u{7F}'), glyph('?'));
    }

    #[test]
    fn the_spec_appendix_matches_the_table() {
        let spec = std::fs::read_to_string("../../docs/fgce.md").expect("read fgce.md");
        let appendix = spec
            .split("## Приложение A.")
            .nth(1)
            .expect("appendix A is missing");
        let mut rows = Vec::new();
        for line in appendix.lines() {
            if !line.starts_with("| `0x") {
                continue;
            }
            let cells: Vec<&str> = line.split('|').map(str::trim).collect();
            let code = u32::from_str_radix(cells[1].trim_matches('`').trim_start_matches("0x"), 16)
                .expect("glyph code");
            let values: Vec<u8> = cells[3]
                .trim_matches('`')
                .split(',')
                .map(|value| {
                    u8::from_str_radix(value.trim().trim_start_matches("0x"), 16)
                        .expect("glyph byte")
                })
                .collect();
            rows.push((code, values));
        }
        assert_eq!(rows.len(), GLYPHS.len(), "the appendix has every glyph");
        for (index, (code, values)) in rows.iter().enumerate() {
            assert_eq!(*code, 0x20 + index as u32);
            assert_eq!(
                values.as_slice(),
                GLYPHS[index].as_slice(),
                "glyph 0x{code:02X}"
            );
        }
    }

    #[test]
    fn text_metrics_are_pinned() {
        assert_eq!(text_width("#123", 1), 23);
        assert_eq!(text_width("#123", 3), 69);
        assert_eq!(text_height(1), 7);
        assert_eq!(text_height(3), 21);
    }
}
